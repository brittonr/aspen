//! Authority delegation denial cases.

pub(super) struct DenyCase<'a> {
    pub(super) name: &'a str,
    pub(super) grant_peer: Option<&'a str>,
    pub(super) grant_node: &'a str,
    pub(super) grant_operations: &'a [&'a str],
    pub(super) target_ref: Option<&'a str>,
    pub(super) target_scope: &'a str,
    pub(super) resource_scope: &'a str,
    pub(super) epoch: u64,
    pub(super) expires_at: Option<u64>,
    pub(super) is_revoked: bool,
    pub(super) sequence: u64,
    pub(super) expected: &'a str,
}

pub(super) struct DenyCaseRefs {
    pub(super) policy_refs: Vec<String>,
    pub(super) resource_refs: Vec<String>,
    pub(super) peer_bootstrap_refs: Vec<String>,
    pub(super) authority_refs: Vec<String>,
}

