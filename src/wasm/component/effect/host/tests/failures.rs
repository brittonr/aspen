use crate::system_extension::NativeCallbackValuePort;

pub(super) struct Observed {
    inner: crate::system_extension::CapabilityCallbackValuePort,
    pub reads: u64,
    fail_label: Option<&'static str>,
}

impl Observed {
    pub fn new(inner: crate::system_extension::CapabilityCallbackValuePort) -> Self {
        Self {
            inner,
            reads: 0,
            fail_label: None,
        }
    }
}

impl NativeCallbackValuePort for Observed {
    fn materialize(
        &mut self,
        value_ref: &str,
        maximum: u64,
    ) -> std::result::Result<crate::system_extension::NativeCallbackValue, crate::system_extension::ValuePortFailure>
    {
        self.reads += 1;
        self.inner.materialize(value_ref, maximum)
    }

    fn publish(
        &mut self,
        value: &crate::system_extension::NativeCallbackValue,
        maximum: u64,
    ) -> std::result::Result<crate::system_extension::ValuePublicationReceipt, crate::system_extension::ValuePortFailure>
    {
        let published = self.inner.publish(value, maximum)?;
        if let Some(label) = self.fail_label {
            let decoded = crate::preserves_rail::parse_canonical_bytes(&value.bytes).expect("host-generated bytes");
            if decoded.collect_simple_record(label, None).is_some() {
                return Err(crate::system_extension::ValuePortFailure::new(
                    crate::system_extension::ValuePortFailureKind::UnknownAfterAcceptance,
                    "injected unknown publication outcome",
                ));
            }
        }
        Ok(published)
    }
}

// r[verify molten.wasm_component_adoption.hostcalls]
#[test]
fn recording_uncertainty_poisoning_prevents_dispatch_or_retry_at_each_boundary() {
    for label in [
        "component-host-intent-v1",
        "component-effect-response-v1",
        "component-host-completion-v1",
    ] {
        let fixture = super::support::Fixture::new();
        let bytes = fixture.request(0);
        let signature = fixture.sign(&bytes);
        let services = fixture.services();
        let current = fixture.current(&services, &signature);
        let mut values = Observed::new(fixture.values());
        values.fail_label = Some(label);
        let mut session = fixture.session();
        assert!(session.invoke(&bytes, &current, &mut values).is_err());
        assert!(session.is_poisoned());
        assert_eq!(values.reads, u64::from(label != "component-host-intent-v1"));
        let before = values.reads;
        assert!(session.invoke(&bytes, &current, &mut values).is_err());
        assert_eq!(values.reads, before, "uncertainty cannot cause a second read");
    }
}

// r[verify molten.wasm_component_adoption.hostcalls]
#[test]
fn monotone_sequence_and_finite_budget_hold_after_a_policy_denial() {
    let fixture = super::support::Fixture::new();
    let zero = fixture.request(0);
    let signature = basalt::ucan::SignerSignature::from_bytes([0; 64]);
    let services = fixture.services();
    let current = fixture.current(&services, &signature);
    let mut values = Observed::new(fixture.values());
    let mut session = fixture.session();
    assert!(session.invoke(&fixture.request(1), &current, &mut values).is_err());
    session.invoke(&zero, &current, &mut values).expect("first denied request recorded");
    assert!(session.invoke(&zero, &current, &mut values).is_err());
    session.invoke(&fixture.request(1), &current, &mut values).expect("second denial recorded");
    assert!(session.invoke(&fixture.request(2), &current, &mut values).is_err());
    assert_eq!(values.reads, 0);
}

#[test]
fn capability_value_port_checks_byte_bounds_identity_and_no_follow() {
    let fixture = super::support::Fixture::new();
    let mut values = fixture.values();
    let reference = crate::preserves_rail::canonical_hash(&fixture.output).expect("object ref");
    assert!(values.materialize(&reference, 1).is_err());
    let wrong = crate::system_extension::NativeCallbackValue {
        value_ref: reference.clone(),
        bytes: b"wrong".to_vec(),
    };
    assert!(values.publish(&wrong, 4_096).is_err());
    let actual = values.materialize(&reference, 4_096).expect("original bytes unchanged");
    assert_eq!(
        crate::preserves_rail::parse_canonical_bytes(&actual.bytes).expect("canonical bytes"),
        fixture.output
    );
}

#[test]
fn capability_value_port_rejects_a_substituted_leaf_symlink() {
    let fixture = super::support::Fixture::new();
    let mut values = fixture.values();
    let reference = crate::preserves_rail::canonical_hash(&fixture.output).expect("object ref");
    let digest = reference.strip_prefix("blake3:").expect("BLAKE3");
    let path = format!("values/{digest}.preserves");
    let root = fixture.workspace.ledger().expect("ledger capability");
    root.dir().remove_file(&path).expect("remove owned value");
    root.dir().symlink("absent-target", &path).expect("substitute owned leaf");
    assert!(values.materialize(&reference, 4_096).is_err());
}
