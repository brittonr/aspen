#!/usr/bin/env python3
"""Normalize only the three authorized Noble manifests; original blobs stay intact.

Run before first source import with --source CHECKOUT, or afterward without it.
No upstream files are changed and no third-party dependency is introduced.
"""
import argparse
from pathlib import Path
import tomllib

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
parser.add_argument("--source", type=Path)
args = parser.parse_args()
destination = args.root / "vendor/noble-pure"
source = args.source or destination
workspace = tomllib.loads((source / ("Cargo.toml" if args.source else "Cargo.toml.orig")).read_text())["workspace"]["package"]
for name in ("noble-kernel", "noble-contracts", "noble-ngraph"):
    relative = Path("crates") / name / "Cargo.toml"
    original = source / (relative if args.source else Path(str(relative) + ".orig"))
    package = tomllib.loads(original.read_text())["package"]
    lines = ["# Generated by scripts/normalize-noble-manifests.py; upstream blob: Cargo.toml.orig", "[package]", f'name = "{name}"']
    for key in ("version", "edition", "publish"):
        value = workspace[key]
        lines.append(f'{key} = {str(value).lower() if isinstance(value, bool) else chr(34) + value + chr(34)}')
    if "description" in package:
        import json
        lines.append("description = " + json.dumps(package["description"]))
    lines += ['license = "AGPL-3.0-or-later"', "", "[dependencies]"]
    if name != "noble-kernel":
        lines.append('noble-kernel = { path = "../noble-kernel" }')
    if name == "noble-ngraph":
        lines.append('noble-contracts = { path = "../noble-contracts" }')
    lines += ["", "[lints.rust]", 'unsafe_code = "forbid"', ""]
    target = destination / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines))
